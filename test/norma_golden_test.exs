    {"userinfo user pass", "http://user:pass@example.com", %{}, "http://example.com"},
    {"userinfo with port 8080 masked", "http://user:pass@example.com:8080/path", %{},
     "http://example.com:8080/path"},
    {"userinfo with port 3000", "http://user:pass@example.com:3000/path", %{},
     "http://example.com:3000/path"},
    {"userinfo https", "https://user@example.com/x", %{}, "https://example.com/x"},
    {"empty string", "", %{}, ""},
    {"dot only", ".", %{}, "http://."},
    {"space", " ", %{}, " "},
    {"not url word", "example", %{}, "example"},
    {"ip host", "http://127.0.0.1", %{}, "http://127.0.0.1"},
    {"ip host port", "http://127.0.0.1:3000", %{}, "http://127.0.0.1:3000"},
    {"ipv6", "http://[::1]", %{}, "http://[::1]"},
    {"ipv6 port", "http://[::1]:8080", %{}, "http://[::1]:8080"},
    {"full combo remove_www force_root remove_fragment", "//www.mazing.studio:1337/test#test",
     %{force_root_path: true, remove_fragment: true, remove_www: true},
     "http://mazing.studio:1337/"},
    {"combo downcase remove_www remove_fragment slash",
     "HTTPS://WWW.Example.COM:8443/path/to?b=2&a=1#frag",
     %{add_trailing_slash: true, remove_fragment: true, remove_www: true},
     "https://www.example.com:8443/path/to/?b=2&a=1"},
    {"combo remove scheme www fragment", "https://www.example.com/x#y",
     %{remove_fragment: true, remove_scheme: true, remove_www: true}, "example.com/x"}
  ]

  for {desc, input, opts, expected} <- @corpus do
    @desc desc
    @input input
    @opts opts
    @expected expected

    test "golden: #{@desc}" do
      assert Norma.normalize(@input, @opts) == @expected
    end
  end
end
