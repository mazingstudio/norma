    {"idn punycode host", "http://xn--mnchen-3ya.de", %{}, "http://xn--mnchen-3ya.de"},
    {"idn path cafe", "http://example.com/café", %{}, "http://example.com/café"},
    {"idn query cafe", "http://example.com?q=café", %{}, "http://example.com?q=caf%C3%A9"},
