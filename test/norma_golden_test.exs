    {"dot segments", "http://example.com/a/./b/../c", %{}, "http://example.com/a/c"},
    {"add_trailing_slash bare", "http://example.com", %{add_trailing_slash: true},
     "http://example.com/"},
    {"add_trailing_slash path", "http://example.com/test", %{add_trailing_slash: true},
     "http://example.com/test/"},
    {"add_trailing_slash already", "http://example.com/test/", %{add_trailing_slash: true},
     "http://example.com/test/"},
    {"add_trailing_slash file", "http://example.com/sitemap.xml", %{add_trailing_slash: true},
     "http://example.com/sitemap.xml"},
    {"add_trailing_slash file frag", "http://example.com/top.html#faqs?p=2",
     %{add_trailing_slash: true}, "http://example.com/top.html#faqs?p=2"},
    {"add_trailing_slash frag query weird", "http://example.com/test#faqs?page=2",
     %{add_trailing_slash: true}, "http://example.com/test/#faqs?page=2"},
    {"force_root_path", "http://example.com/foo/bar", %{force_root_path: true},
     "http://example.com/"},
    {"force_root_path already", "http://example.com/", %{force_root_path: true},
     "http://example.com/"},
    {"www keep", "https://www.example.com", %{}, "https://www.example.com"},
    {"www remove", "https://www.example.com", %{remove_www: true}, "https://example.com"},
    {"www remove with path", "https://www.example.com/x", %{remove_www: true},
     "https://example.com/x"},
    {"www false", "https://www.example.com", %{remove_www: false}, "https://www.example.com"},
    {"WWW uppercase prefix with remove_www", "https://WWW.example.com", %{remove_www: true},
     "https://www.example.com"},
    {"upcase host default", "HTTP://EXAMPLE.COM/DIR?PAGE=2", %{},
     "http://example.com/DIR?PAGE=2"},
    # D8: downcase_host option removed; D6 always folds host case
    {"downcase_host true", "HTTP://EXAMPLE.COM/DIR?PAGE=2", %{},
     "http://example.com/DIR?PAGE=2"},
    {"downcase_host false", "HTTP://EXAMPLE.COM/DIR?PAGE=2", %{},
     "http://example.com/DIR?PAGE=2"},
    {"mailto", "mailto:joe@example.com", %{}, "mailto:joe@example.com"},
    {"mailto no at", "mailto:joe", %{}, "mailto:joe"},
